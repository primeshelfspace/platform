/**
 * The handful of icons this app's pages need, inlined as SVG.
 *
 * The admin app imports these same glyphs from lucide-react; this app does
 * not, and deliberately: every dependency here is a PCI scope question (see
 * apps/payment/package.json's own note), and four icon paths do not justify
 * pulling an icon library into the bundle a customer's card entry loads
 * beside. Paths are lucide's, so the two apps still draw the same marks.
 */

type IconProps = { className?: string };

function Svg({ className, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
    >
      {children}
    </svg>
  );
}

